#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
check_my_table.py  —  turn your filled CSV into the Lua reward table.

Usage
-----
  python3 tests/check_my_table.py                # validate only
  python3 tests/check_my_table.py --write        # validate + write lua/rz_rewards_table.lua
  python3 tests/check_my_table.py --csv my.csv   # custom csv path

CSV columns (Arabic header row is fine, order matters):
  type , slot , item_key , qty , note
  type  = daily | hourly
  slot  = 1,2,3...   (day number / hour number)
  qty   = integer 1..99
Lines starting with # are ignored.
"""

import argparse
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LUA_ENGINE = os.path.join(ROOT, "lua", "rz_rewards.lua")
LUA_TABLE = os.path.join(ROOT, "lua", "rz_rewards_table.lua")
DEFAULT_CSV = os.path.join(ROOT, "جدول-المكافآت.csv")

BUILTIN_KEYS = [
    "repair_kit", "potion_hp", "potion_mp", "exp10", "exp20", "exp30",
    "drop10", "teleport_scroll", "res_scroll", "pet_food", "buff_scroll",
]


def known_keys():
    """Read M.items keys from the engine so we never drift apart."""
    try:
        src = open(LUA_ENGINE, encoding="utf-8").read()
        block = src.split("M.items = {", 1)[1].split("}", 1)[0]
        keys = re.findall(r"(\w+)\s*=", block)
        return keys or BUILTIN_KEYS
    except Exception:
        return BUILTIN_KEYS


def parse(path):
    rows, errors = [], []
    with open(path, encoding="utf-8-sig", newline="") as f:
        for lineno, raw in enumerate(csv.reader(f), start=1):
            if not raw or not "".join(raw).strip():
                continue
            if "".join(raw).lstrip().startswith("#"):
                continue
            if raw[0].strip().lower() in ("النوع", "type"):
                continue
            cells = [c.strip() for c in raw] + ["", "", "", "", ""]
            typ, slot, key, qty = cells[0].lower(), cells[1], cells[2], cells[3]
            if typ not in ("daily", "hourly"):
                errors.append(f"line {lineno}: type must be daily/hourly → got '{typ}'")
                continue
            if not slot.isdigit() or int(slot) < 1:
                errors.append(f"line {lineno}: slot must be 1,2,3... → got '{slot}'")
                continue
            if not key:
                errors.append(f"line {lineno}: item key is empty")
                continue
            if not qty.isdigit() or not (1 <= int(qty) <= 99):
                errors.append(f"line {lineno}: qty must be 1..99 → got '{qty}'")
                continue
            rows.append((typ, int(slot), key, int(qty)))
    return rows, errors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=DEFAULT_CSV)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    if not os.path.exists(args.csv):
        print(f"CSV not found: {args.csv}")
        return 2

    keys = set(known_keys())
    rows, errors = parse(args.csv)

    unknown = sorted({r[2] for r in rows if r[2] not in keys})
    for u in unknown:
        errors.append(f"unknown item key '{u}' (allowed: {', '.join(sorted(keys))})")

    if errors:
        print("VALIDATION FAILED\n" + "\n".join("  - " + e for e in errors))
        return 1

    if not rows:
        print("VALIDATION: file is empty (nothing will be granted)")
        return 0

    cycles = {"daily": {}, "hourly": {}}
    for typ, slot, key, qty in rows:
        cycles[typ].setdefault(slot, []).append((key, qty))

    print("VALIDATION OK")
    for typ in ("daily", "hourly"):
        slots = sorted(cycles[typ])
        if not slots:
            print(f"  {typ}: (empty)")
            continue
        print(f"  {typ}: {len(slots)} slot(s)")
        for s in slots:
            items = ", ".join(f"{k} x{q}" for k, q in cycles[typ][s])
            print(f"    [{s}] {items}")

    if args.write:
        out = [
            "-- ============================================================",
            "--  rz_rewards_table.lua   (generated by tests/check_my_table.py)",
            "--  Edit the CSV, then re-run the generator.  ASCII ONLY",
            "-- ============================================================",
            "",
            "RZ_TABLE = {",
        ]
        for typ, lua_name in (("daily", "daily"), ("hourly", "hourly")):
            out.append(f"  {lua_name} = {{")
            for s in sorted(cycles[typ]):
                label = f"{'day' if typ == 'daily' else 'hour'} {s}"
                out.append(f'    [{s}] = {{ label = "{label}", items = {{')
                for k, q in cycles[typ][s]:
                    out.append(f'      {{ k = "{k}", n = {q} }},')
                out.append("    } },")
            out.append("  },")
        out.append("}")
        open(LUA_TABLE, "w", encoding="utf-8").write("\n".join(out) + "\n")
        print(f"\nWROTE  {LUA_TABLE}")
    else:
        print("\n(dry run — add --write to generate lua/rz_rewards_table.lua)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
